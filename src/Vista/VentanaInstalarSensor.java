    public VentanaInstalarSensor() {
        setContentPane(contentPane);
        setTitle("Instalar sensor");
        setModal(true);
        getRootPane().setDefaultButton(buttonInstalar);

        // Desplegar estaciones
        for (String codigo : instituto.getCodigosEstaciones()) {
            boxEstacion.addItem(codigo);
        }

        panelTipoSensor.setLayout(new GridLayout(2, 3));

        for (TipoSensor tipo : TipoSensor.values()) {
            JRadioButton radio = new JRadioButton(tipo.toString());
            radio.setActionCommand(tipo.name());

            buttonGroupTipos.add(radio);
            panelTipoSensor.add(radio);
        }

        buttonInstalar.addActionListener(new ActionListener() {
            public void actionPerformed(ActionEvent e) {
                onInstalar();
            }
        });

        // Salir en esc, x y buttonSalir
        buttonCancelar.addActionListener(new ActionListener() {
            public void actionPerformed(ActionEvent e) {
                onCancelar();
            }
        });
        setDefaultCloseOperation(DO_NOTHING_ON_CLOSE);
        addWindowListener(new WindowAdapter() {
            public void windowClosing(WindowEvent e) {
                onCancelar();
            }
        });
        contentPane.registerKeyboardAction(new ActionListener() {
            public void actionPerformed(ActionEvent e) {
                onCancelar();
            }
        }, KeyStroke.getKeyStroke(KeyEvent.VK_ESCAPE, 0), JComponent.WHEN_ANCESTOR_OF_FOCUSED_COMPONENT);
    }


    private void onInstalar() {
        String codigo = textFieldCodigo.getText();
        String marca = textFieldMarca.getText();
        String modelo = textFieldModelo.getText();
        String codigoEstacion = (String) boxEstacion.getSelectedItem();

        if (!codigo.trim().isEmpty() && !marca.trim().isEmpty() && !modelo.trim().isEmpty() && codigoEstacion != null && buttonGroupTipos.getSelection() != null) {
            try {
                // Para conseguir el tipo de sensor seleccionado
                TipoSensor tipo = TipoSensor.valueOf(buttonGroupTipos.getSelection().getActionCommand());
                instituto.instalaSensor(codigo.trim(), marca.trim(), modelo.trim(), tipo, codigoEstacion);
                JOptionPane.showMessageDialog(this, "Sensor instalado correctamente.", "Mensaje", JOptionPane.INFORMATION_MESSAGE);
                limpiar();
            } catch (MeteorologiaException e) {
                JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Uno o más datos ausentes.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiar() {
        textFieldCodigo.setText("");
        textFieldMarca.setText("");
        textFieldModelo.setText("");
        buttonGroupTipos.clearSelection();
        if (boxEstacion.getItemCount() > 0) {
            boxEstacion.setSelectedIndex(0);
        }
    }

    private void onCancelar() {
        dispose();
    }

    public static void display() {
        VentanaInstalarSensor dialog = new VentanaInstalarSensor();
        dialog.pack();
        dialog.setLocationRelativeTo(null);
        dialog.setVisible(true);
    }

